// Financial link checks in isolated PostgreSQL; no production database access.
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const { PGlite } = await import(process.argv[2] || "@electric-sql/pglite");
const db = new PGlite();
const admin = "00000000-0000-4000-8000-000000000001";
await db.exec(`
  create role anon; create role authenticated; create role service_role;
  create schema auth;
  create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('test.uid', true), '')::uuid $$;
  create table users (id uuid primary key, auth_user_id uuid, role text);
  insert into users values ('${admin}', '${admin}', 'admin');
  select set_config('test.uid', '${admin}', false);
  create table fabrics (id uuid primary key);
  create table orders (id uuid primary key);
`);
const migration = async name => db.exec(await readFile(new URL(`../supabase/migrations/${name}`, import.meta.url), "utf8"));
for (const name of ["20260403_create_design_queue_entries.sql", "20260325_create_quotation_drafts.sql", "20260323_create_factory_deposit_orders.sql", "20260521_split_design_deposit_and_discount_fields.sql", "20261020_link_queue_customer_documents.sql"]) await migration(name);
const one = async (sql, args = []) => (await db.query(sql, args)).rows[0];
const legacy = await one(`select * from create_design_queue_entry(p_customer_name => 'Legacy', p_notes => '100,000')`);
const historical = await one(`insert into quotation_drafts(created_by_user_id,quote_date,design_queue_entry_id,design_deposit) values ($1,'2026-10-15',$2,120000) returning *`, [admin, legacy.id]);
await migration("20261021_add_queue_design_deposits.sql");
await migration("20261021_add_queue_design_deposits.sql");
assert.equal((await one(`select * from quotation_drafts where id=$1`, [historical.id])).design_deposit, "120000.00");
const oldQueue = await one(`select * from design_queue_entries where id=$1`, [legacy.id]);
assert.equal(oldQueue.design_payment_type, null);
assert.equal(oldQueue.design_deposit_amount, null);
const create = (mode, amount) => one(`select * from create_design_queue_entry(p_queue_date => '2026-10-15', p_customer_name => 'QA Deposit', p_design_payment_type => $1, p_design_deposit_amount => $2)`, [mode, amount]);
const free = await create("free", null);
const paid = await create("deposit", 100000.50);
assert.equal(free.design_deposit_amount, null);
assert.equal(paid.design_deposit_amount, "100000.50");
for (const [mode, amount] of [["deposit", null], ["deposit", 0], ["deposit", -1], ["deposit", "NaN"], ["deposit", 0.001], ["free", 100000], [null, 100000], ["invalid", null]]) await assert.rejects(create(mode, amount));
const quote = queueId => one(`insert into quotation_drafts(created_by_user_id,quote_date,design_queue_entry_id,design_deposit) values ($1,'2026-10-15',$2,999999) returning *`, [admin, queueId]);
const freeQuote = await quote(free.id);
const paidQuote = await quote(paid.id);
assert.equal(freeQuote.design_deposit, "0.00", "A free queue clears stale fees");
assert.equal(paidQuote.design_deposit, "100000.50", "The backend uses the recorded received amount");
assert.equal((await quote(legacy.id)).design_deposit, "0.00", "Unknown legacy notes never become a financial deduction");
const results = (await db.query(`select * from search_design_queue_customers('QA Deposit')`)).rows;
assert.equal(results.find(r => r.id === paid.id).design_deposit_amount, "100000.50");
assert.equal(results.find(r => r.id === free.id).design_payment_type, "free");
// Editing source money never retroactively changes saved financial records.
await db.query(`update design_queue_entries set design_deposit_amount=200000 where id=$1`, [paid.id]);
await db.query(`update quotation_drafts set notes='Edit only' where id=$1`, [paidQuote.id]);
assert.equal((await one(`select * from quotation_drafts where id=$1`, [paidQuote.id])).design_deposit, "100000.50");
await db.query(`update quotation_drafts set design_queue_entry_id=$1 where id=$2`, [free.id, paidQuote.id]);
assert.equal((await one(`select * from quotation_drafts where id=$1`, [paidQuote.id])).design_deposit, "0.00");
await db.query(`update quotation_drafts set design_queue_entry_id=$1 where id=$2`, [paid.id, paidQuote.id]);
assert.equal((await one(`select * from quotation_drafts where id=$1`, [paidQuote.id])).design_deposit, "200000.00");
const deposit = await one(`insert into factory_deposit_orders(quotation_draft_id,deposit_no,deposit_date,design_deposit) values ($1,'','2026-10-15',999999) returning *`, [paidQuote.id]);
assert.equal(deposit.design_deposit, "200000.00");
// Changing to free must clear the amount in the same write.
await assert.rejects(db.query(`update design_queue_entries set design_payment_type='free' where id=$1`, [paid.id]));
await db.query(`update design_queue_entries set design_payment_type='free', design_deposit_amount=null where id=$1`, [paid.id]);
assert.equal((await quote(paid.id)).design_deposit, "0.00");
assert.equal((await one(`select * from quotation_drafts where id=$1`, [paidQuote.id])).design_deposit, "200000.00");
// Old callers can still omit the new optional arguments without inventing a fee.
assert.equal((await one(`select * from create_design_queue_entry()`)).design_payment_type, null);
await db.exec(`grant usage on schema public, auth to authenticated; grant execute on function auth.uid() to authenticated; grant select on users, design_queue_entries to authenticated; set role authenticated;`);
assert.equal((await db.query(`select * from search_design_queue_customers('QA Deposit')`)).rows.length, 2);
await db.exec(`select set_config('test.uid', '00000000-0000-4000-8000-000000000099', false)`);
assert.equal((await db.query(`select * from search_design_queue_customers('QA Deposit')`)).rows.length, 0);
await assert.rejects(db.query(`select create_design_queue_entry(p_design_payment_type => 'free')`));
await db.exec(`reset role; set role anon;`);
await assert.rejects(db.query(`select * from search_design_queue_customers('QA Deposit')`));
await db.exec(`reset role;`);
await db.close();
console.log("Design deposits passed: free/paid validation, exact amounts, search fields, quotation/deposit inheritance, stale fee clearing, immutable history, legacy preservation, repeat migration and RLS.");
